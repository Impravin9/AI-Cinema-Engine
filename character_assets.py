"""External Blender character asset ingestion for the AI Cinema Engine.

The engine owns scene direction and root motion; authored character meshes/armatures
come from licensed .blend assets. This module deliberately does not assume a vendor's
bone names or silently retarget incompatible rigs.
"""
from __future__ import annotations

import json
from pathlib import Path


def validate_character_asset(path: str | Path) -> Path:
    """Validate an authored Blender asset before spawning Blender."""
    asset = Path(path).expanduser().resolve()
    if not asset.is_file():
        raise FileNotFoundError(f"Character asset does not exist: {asset}")
    if asset.suffix.lower() != ".blend":
        raise ValueError("Character assets must currently be Blender .blend files; FBX/glTF import is not enabled yet.")
    if asset.stat().st_size < 1024:
        raise ValueError(f"Character asset is suspiciously small or incomplete: {asset}")
    return asset


BLENDER_IMPORT_SOURCE = r'''
# Optional authored character override. The imported rig is preserved as supplied;
# no guessed bone mapping or destructive re-rigging is performed.
if character_asset:
    from mathutils import Vector
    asset_path = os.path.abspath(character_asset)
    if not os.path.isfile(asset_path):
        raise RuntimeError("Character asset disappeared before Blender import: " + asset_path)
    before_import = set(bpy.data.objects)
    with bpy.data.libraries.load(asset_path, link=False) as (data_from, data_to):
        data_to.objects = list(data_from.objects)
    imported = [obj for obj in data_to.objects if obj is not None]
    for obj in imported:
        if obj.name not in s.objects:
            s.collection.objects.link(obj)
    imported_meshes = [obj for obj in imported if obj.type == "MESH"]
    imported_armatures = [obj for obj in imported if obj.type == "ARMATURE"]
    if not imported_meshes:
        raise RuntimeError("The selected .blend contains no mesh character objects.")
    # Parent imported top-level objects under a neutral cinematic root while
    # preserving their authored world transforms and internal armature hierarchy.
    asset_root = bpy.data.objects.new("AUTHORED_CHARACTER_ROOT", None)
    s.collection.objects.link(asset_root)
    for obj in imported:
        if obj.parent is None:
            world = obj.matrix_world.copy()
            obj.parent = asset_root
            obj.matrix_world = world
    depsgraph = bpy.context.evaluated_depsgraph_get()
    bpy.context.view_layer.update()
    corners = []
    for obj in imported_meshes:
        evaluated = obj.evaluated_get(depsgraph)
        corners.extend([evaluated.matrix_world @ Vector(corner) for corner in evaluated.bound_box])
    if not corners:
        raise RuntimeError("Could not calculate character bounds from imported meshes.")
    min_v = Vector((min(v.x for v in corners), min(v.y for v in corners), min(v.z for v in corners)))
    max_v = Vector((max(v.x for v in corners), max(v.y for v in corners), max(v.z for v in corners)))
    height = max_v.z - min_v.z
    if height <= 0.001:
        raise RuntimeError("Imported character has invalid vertical bounds.")
    asset_root.location = (-(min_v.x + max_v.x) * 0.5, -(min_v.y + max_v.y) * 0.5, -min_v.z)
    asset_root.scale = (2.75 / height,) * 3
    asset_root.parent = root
    # Disable only the procedural hero generated by this engine, not the set.
    for obj in procedural_character_objects:
        if obj.type == "MESH":
            obj.hide_render = True
            obj.hide_viewport = True
    print("[character] Imported authored asset:", asset_path)
    print("[character] Meshes:", len(imported_meshes), "| armatures:", len(imported_armatures))
    if not imported_armatures:
        print("[character] WARNING: no armature found; character will be root-motion only.")
    else:
        print("[character] Rig preserved. Vendor-specific facial/body controls are not yet mapped.")
else:
    print("[character] Using procedural fallback. Pass --character-asset <file.blend> for an authored model.")
'''


def inject_character_import(source: str) -> str:
    marker = "# Directed film timeline: joint-based gait, body weight shift, acting and camera beats."
    if marker not in source:
        raise RuntimeError("Cannot find animation timeline marker for character asset integration.")
    return source.replace(marker, BLENDER_IMPORT_SOURCE + "\n" + marker, 1)
